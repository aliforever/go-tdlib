package tdlib

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"sync"
	"sync/atomic"

	"github.com/aliforever/go-tdlib/v2/td"
)

// defaultInboxSize bounds the per-client queue between the manager receive
// loop and the client's dispatch goroutine. When full, the oldest message
// is dropped (see Client.enqueue).
const defaultInboxSize = 256

// NewExtra generates a request correlation key for the @extra envelope
// field. It is 16 bytes of crypto/rand hex — collision-free in practice,
// stdlib-only, so the module carries no uuid dependency. The caller of
// roundTrip generates the key; roundTrip never invents one itself.
func NewExtra() string {
	var b [16]byte
	if _, err := rand.Read(b[:]); err != nil {
		// crypto/rand.Read only fails when the OS entropy source is broken;
		// there is no sane fallback for a correlation key.
		panic("tdlib: crypto/rand unavailable: " + err.Error())
	}
	return hex.EncodeToString(b[:])
}

// Client is the runtime core of one TDLib client: request/response
// correlation, update routing and lifecycle. The typed generic API
// (Client.Do, On[U]) is layered on top in a later phase; everything here is
// type-erased and mockable via Transport.
type Client struct {
	id        int
	transport Transport

	// inbox decouples the manager receive loop from dispatch. Bounded; see
	// enqueue for the drop-oldest policy.
	inbox chan []byte

	pending *pendingRegistry
	router  *router

	// rawHooks receive every non-response message (tdType, raw JSON) before
	// the typed router. Used by tooling (e.g. the MCP server) that needs an
	// untyped view of all updates. Must be fast: called from dispatchLoop.
	rawHooksMu sync.RWMutex
	rawHooks   []func(ctx context.Context, tdType string, raw json.RawMessage)

	// ctx governs the client's lifetime: the dispatch loop, subscriber
	// delivery and roundTrip all end when it is cancelled by Close.
	ctx       context.Context
	cancel    context.CancelFunc
	closeOnce sync.Once

	// onInboxDrop is installed by Manager.Register; may be nil.
	onInboxDrop  func(clientID int, dropped int64)
	inboxDropped atomic.Int64
}

// NewClient creates a client around an existing TDLib client ID and
// transport. It starts the dispatch goroutine immediately; Close releases
// it.
func NewClient(id int, t Transport) *Client {
	ctx, cancel := context.WithCancel(context.Background())
	c := &Client{
		id:        id,
		transport: t,
		inbox:     make(chan []byte, defaultInboxSize),
		pending:   newPendingRegistry(),
		router:    newRouter(),
		ctx:       ctx,
		cancel:    cancel,
	}
	go c.dispatchLoop()
	return c
}

// ID returns the TDLib client identifier.
func (c *Client) ID() int { return c.id }

// roundTrip sends one marshalled request envelope and waits for its
// response. extra is the @extra correlation key, generated by the caller
// (see NewExtra); the same key must already be embedded in payload.
//
// A response with @type "error" is decoded into *td.Error and returned as
// the error, so callers can use errors.As. ctx cancellation or Close
// aborts the wait; the pending entry is removed on every path.
func (c *Client) roundTrip(ctx context.Context, payload []byte, extra string) (json.RawMessage, error) {
	if c.ctx.Err() != nil {
		return nil, ErrClientClosed
	}
	call := c.pending.register(extra)
	defer c.pending.remove(extra)

	if err := c.transport.Send(c.id, payload); err != nil {
		return nil, err
	}

	select {
	case <-ctx.Done():
		return nil, ctx.Err()
	case <-c.ctx.Done():
		return nil, ErrClientClosed
	case res := <-call.ch:
		if res.err != nil {
			return nil, res.err
		}
		var head struct {
			Type string `json:"@type"`
		}
		if err := json.Unmarshal(res.raw, &head); err != nil {
			return nil, err
		}
		if head.Type == "error" {
			var tdErr td.Error
			if err := json.Unmarshal(res.raw, &tdErr); err != nil {
				return nil, err
			}
			return nil, &tdErr
		}
		return res.raw, nil
	}
}

// Close shuts the client down: the dispatch loop stops, every in-flight
// call fails with ErrClientClosed and all update subscribers are cancelled.
// It is idempotent. The manager (if any) drops further messages for this
// client once it is unregistered or closed.
func (c *Client) Close() error {
	c.closeOnce.Do(func() {
		c.cancel()
		c.pending.failAll(ErrClientClosed)
		c.router.closeAll()
	})
	return nil
}

// enqueue is called by the manager receive loop to hand this client one raw
// message. It never blocks the manager: when the bounded inbox is full the
// oldest message is dropped and onInboxDrop is invoked with the cumulative
// drop count. A closed client silently discards messages.
func (c *Client) enqueue(raw []byte) {
	select {
	case <-c.ctx.Done():
		return
	default:
	}
	select {
	case c.inbox <- raw:
		return
	default:
	}
	select {
	case <-c.inbox:
		n := c.inboxDropped.Add(1)
		if c.onInboxDrop != nil {
			c.onInboxDrop(c.id, n)
		}
	default:
	}
	select {
	case c.inbox <- raw:
	case <-c.ctx.Done():
	}
}

// dispatchLoop is the client's single consumer goroutine: no goroutine per
// update (v1 spawned one per handler).
func (c *Client) dispatchLoop() {
	for {
		select {
		case <-c.ctx.Done():
			return
		case raw := <-c.inbox:
			c.dispatch(raw)
		}
	}
}

// dispatch peeks only @type and @extra: a message carrying @extra completes
// a pending call, anything else goes to the update router.
func (c *Client) dispatch(raw []byte) {
	var head struct {
		Type  string `json:"@type"`
		Extra string `json:"@extra"`
	}
	if err := json.Unmarshal(raw, &head); err != nil {
		return // malformed message: drop it, keep the loop alive
	}
	if head.Extra != "" {
		c.pending.deliver(head.Extra, raw)
		return
	}
	c.rawHooksMu.RLock()
	hooks := c.rawHooks
	c.rawHooksMu.RUnlock()
	for _, h := range hooks {
		h(c.ctx, head.Type, raw)
	}
	c.router.dispatch(c.ctx, head.Type, raw)
}

// OnRaw registers a hook receiving every incoming message that is not a
// request response: its @type discriminator and raw JSON. The hook runs on
// the client's dispatch goroutine and must not block; copy the raw slice if
// retaining it. Intended for tooling that needs an untyped update stream.
func (c *Client) OnRaw(h func(ctx context.Context, tdType string, raw json.RawMessage)) {
	c.rawHooksMu.Lock()
	c.rawHooks = append(c.rawHooks, h)
	c.rawHooksMu.Unlock()
}
