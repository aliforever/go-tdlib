package main

import (
	"fmt"
	"path/filepath"
	"strings"
)

const facadeHeader = `// Code generated by internal/gen; DO NOT EDIT.

// facade_gen.go carries one thin typed method per TDLib function, each a
// one-line delegation to Client.Do. Hand-written Client members win: a
// function whose name collides (e.g. close vs Client.Close) is skipped and
// reported by the generator.

package tdlib
`

// facadeReserved lists existing Client members a facade method must not
// shadow. Requests are PascalCase, so only exported collisions are possible
// in practice; roundTrip is listed defensively.
var facadeReserved = map[string]bool{
	"ID": true, "Close": true, "NewClient": true,
	"Do": true, "DoAsync": true, "DoRaw": true,
	"On": true, "Updates": true, "Next": true, "Messages": true,
	"roundTrip": true,
}

// goKeywords that cannot be used as parameter names. TL schemas use "type"
// as a field name (e.g. getCreatedPublicChats), so the facade renames such
// parameters deterministically.
var goKeywords = map[string]bool{
	"break": true, "case": true, "chan": true, "const": true,
	"continue": true, "default": true, "defer": true, "else": true,
	"fallthrough": true, "for": true, "func": true, "go": true,
	"goto": true, "if": true, "import": true, "interface": true,
	"map": true, "package": true, "range": true, "return": true,
	"select": true, "struct": true, "switch": true, "type": true,
	"var": true,
}

// facadeParamName derives a lowerCamel parameter name from a snake_case TL
// field name: chat_id -> chatId. Go keywords and "ctx" get a trailing
// underscore (type -> type_).
func facadeParamName(tlName string) string {
	n := goFieldName(tlName)
	n = strings.ToLower(n[:1]) + n[1:]
	if goKeywords[n] || n == "ctx" {
		n += "_"
	}
	return n
}

// emitFacade writes facade_gen.go into the v2 module root (package tdlib):
// one method per request, parameters in schema order, delegating to Do.
// Output is deterministic because s.functions is pre-sorted. It returns the
// number of emitted methods and the names skipped due to collisions with
// existing Client members.
func emitFacade(s *scheme, rootDir string) (int, []string, error) {
	var b strings.Builder
	b.WriteString("import (\n\t\"context\"\n\n\t\"github.com/aliforever/go-tdlib/v2/td\"\n)\n\n")

	emitted := 0
	var skipped []string
	for _, c := range s.functions {
		name := pascal(c.name)
		if facadeReserved[name] {
			skipped = append(skipped, name)
			continue
		}

		params := make([]string, 0, len(c.fields))
		args := make([]string, 0, len(c.fields))
		seen := map[string]bool{}
		for _, f := range c.fields {
			pn := facadeParamName(f.name)
			if seen[pn] {
				return 0, nil, fmt.Errorf("function %s: duplicate facade parameter %s", c.name, pn)
			}
			seen[pn] = true
			params = append(params, pn+" "+s.goTypeIn(f.typ, "td."))
			args = append(args, goFieldName(f.name)+": "+pn)
		}

		fmt.Fprintf(&b, "// %s calls the TDLib function %q; see td.%s for the request docs.\n", name, c.name, name)
		fmt.Fprintf(&b, "func (c *Client) %s(ctx context.Context", name)
		for _, p := range params {
			b.WriteString(", " + p)
		}
		fmt.Fprintf(&b, ") (%s, error) {\n", s.goTypeIn(c.result, "td."))
		fmt.Fprintf(&b, "\treturn c.Do(ctx, td.%s{%s})\n}\n\n", name, strings.Join(args, ", "))
		emitted++
	}

	if err := writeGoFile(rootDir, "facade_gen.go", facadeHeader+b.String()); err != nil {
		return 0, nil, err
	}
	return emitted, skipped, nil
}

// facadeRootDir resolves the v2 module root from the generator directory.
func facadeRootDir(genDir string) string {
	return filepath.Clean(filepath.Join(genDir, "..", ".."))
}
