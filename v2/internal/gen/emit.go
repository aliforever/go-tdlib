// unionClass returns the abstract class a field type resolves to (through
// vector<> wrappers and bare constructor references), or "" when the type
// is not a union container.
func (s *scheme) unionClass(typ string) string {
	for strings.HasPrefix(typ, "vector<") && strings.HasSuffix(typ, ">") {
		typ = typ[len("vector<") : len(typ)-1]
	}
	if _, ok := s.classes[typ]; ok {
		return typ
	}
	if c, ok := s.byName[typ]; ok {
		if _, ok := s.classes[c.result]; ok {
			return c.result
		}
	}
	return ""
}

// emitSchema writes schema_gen.go: one MethodSchema per TDLib function, the
// lookup/search helpers and the data tables. The exported contract (types,
// LookupMethod, AllMethods, SearchMethods) is emitted verbatim; only the
// data changes between regenerations.
func emitSchema(s *scheme, outDir string) error {
	// class -> sorted variant @type names
	variants := map[string][]string{}
	for _, c := range s.entities {
		if _, ok := s.classes[c.result]; ok {
			variants[c.result] = append(variants[c.result], c.name)
		}
	}

	var b strings.Builder
	b.WriteString("import (\n\t\"sort\"\n\t\"strings\"\n)\n\n")

	b.WriteString(`// ParamSchema describes one parameter of a TDLib function.
type ParamSchema struct {
	// Name is the JSON field name (snake_case).
	Name string
	// GoType is the generated Go type, e.g. "int64", "string", "ChatList",
	// "[]int64", "Int64List".
	GoType string
	// IsUnion is true when the parameter is a union container; the caller
	// must supply an object with an "@type" member naming a variant.
	IsUnion bool
	// Variants lists the allowed "@type" constructor names for union params.
	Variants []string
	// Description is the schema doc comment for the parameter.
	Description string
}

// MethodSchema describes one TDLib function.
type MethodSchema struct {
	// Name is the TDLib function name, e.g. "sendMessage".
	Name string
	// Description is the schema doc comment for the function.
	Description string
	// Params are the function parameters in schema order.
	Params []ParamSchema
	// ReturnType is the TDLib result type name, e.g. "Message".
	ReturnType string
}

// LookupMethod returns the schema for a TDLib function by name.
func LookupMethod(name string) (MethodSchema, bool) {
	m, ok := methodSchemas[name]
	return m, ok
}

// AllMethods returns every known method schema, sorted by name.
func AllMethods() []MethodSchema { return allMethods }

// SearchMethods returns up to limit method schemas whose name or
// description contains query (case-insensitive), sorted by name.
func SearchMethods(query string, limit int) []MethodSchema {
	return searchMethods(query, limit)
}

`)

	// Data: one entry per function, sorted by name (s.functions is sorted).
	b.WriteString("var methodSchemas = map[string]MethodSchema{\n")
	for _, c := range s.functions {
		fmt.Fprintf(&b, "\t%q: {\n\t\tName: %q,\n", c.name, c.name)
		if c.doc != "" {
			fmt.Fprintf(&b, "\t\tDescription: %q,\n", c.doc)
		}
		fmt.Fprintf(&b, "\t\tReturnType: %q,\n", c.result)
		if len(c.fields) > 0 {
			b.WriteString("\t\tParams: []ParamSchema{\n")
			for _, f := range c.fields {
				fmt.Fprintf(&b, "\t\t\t{Name: %q, GoType: %q", f.name, s.goType(f.typ))
				if class := s.unionClass(f.typ); class != "" {
					b.WriteString(", IsUnion: true")
					fmt.Fprintf(&b, ", Variants: []string{")
					for i, v := range variants[class] {
						if i > 0 {
							b.WriteString(", ")
						}
						fmt.Fprintf(&b, "%q", v)
					}
					b.WriteString("}")
				}
				if f.doc != "" {
					fmt.Fprintf(&b, ", Description: %q", f.doc)
				}
				b.WriteString("},\n")
			}
			b.WriteString("\t\t},\n")
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")

	// Derived slice and search logic, verbatim on every regeneration.
	b.WriteString(`var allMethods = func() []MethodSchema {
	out := make([]MethodSchema, 0, len(methodSchemas))
	for _, m := range methodSchemas {
		out = append(out, m)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out
}()

// searchMethods matches every whitespace-separated query term as a
// case-insensitive substring of the method name or description, so
// "send photo" finds sendMessageAlbum. allMethods is pre-sorted by name.
func searchMethods(query string, limit int) []MethodSchema {
	if limit <= 0 {
		limit = 20
	}
	terms := strings.Fields(strings.ToLower(query))
	var out []MethodSchema
	for _, m := range allMethods {
		hay := strings.ToLower(m.Name) + "\n" + strings.ToLower(m.Description)
		ok := true
		for _, term := range terms {
			if !strings.Contains(hay, term) {
				ok = false
				break
			}
		}
		if ok {
			out = append(out, m)
			if len(out) >= limit {
				break
			}
		}
	}
	return out
}
`)
	return writeGo(outDir, "schema_gen.go", b.String())
}

func emitUpdates(s *scheme, outDir string) error {
	var b strings.Builder
	b.WriteString("// updateVariantTypes lists every known Update variant @type,\n")
	b.WriteString("// sorted. The client router uses it to register handlers.\n")
	b.WriteString("var updateVariantTypes = []string{\n")
	for _, t := range s.updateTypes {
		fmt.Fprintf(&b, "\t%q,\n", t)
	}
	b.WriteString("}\n\n")
	b.WriteString("// UpdateVariantTypes returns the sorted @type names of all Update\n")
	b.WriteString("// variants known to this build.\n")
	b.WriteString("func UpdateVariantTypes() []string {\n")
	b.WriteString("\treturn append([]string(nil), updateVariantTypes...)\n}\n")
	return writeGo(outDir, "updates_gen.go", b.String())
}
