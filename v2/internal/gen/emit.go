func emitEntities(s *scheme, outDir string) error {
	for start, idx := 0, 1; start < len(s.entities); start, idx = start+entityChunkSize, idx+1 {
		end := start + entityChunkSize
		if end > len(s.entities) {
			end = len(s.entities)
		}
		var b strings.Builder
		for _, c := range s.entities[start:end] {
			emitEntity(&b, s, c)
		}
		if err := writeGo(outDir, fmt.Sprintf("types_gen_%02d.go", idx), b.String()); err != nil {
			return err
		}
	}
	return nil
}

func emitEntity(b *strings.Builder, s *scheme, c ctor) {
	name := pascal(c.name)
	docComment(b, name+" —", c.doc)
	fmt.Fprintf(b, "type %s struct {\n", name)
	for _, f := range c.fields {
		fieldDoc(b, f.doc)
		fmt.Fprintf(b, "\t%s %s `json:%q`\n", goFieldName(f.name), s.goType(f.typ), jsonTagFor(f))
	}
	fmt.Fprintf(b, "}\n\n")
	fmt.Fprintf(b, "// TDType returns the TDLib @type discriminator %q.\n", c.name)
	fmt.Fprintf(b, "func (*%s) TDType() string { return %q }\n\n", name, c.name)

	if _, isClass := s.classes[c.result]; !isClass {
		// Plain structs appear nested inside requests and variants, where
		// TDLib still expects an @type key; union variants get theirs from
		// the container instead, so only plain structs self-inject.
		alias := strings.ToLower(name[:1]) + name[1:] + "Alias"
		fmt.Fprintf(b, "type %s %s\n\n", alias, name)
		fmt.Fprintf(b, "// MarshalJSON injects the @type discriminator TDLib requires\n")
		fmt.Fprintf(b, "// on every nested object.\n")
		fmt.Fprintf(b, "func (v *%s) MarshalJSON() ([]byte, error) {\n", name)
		fmt.Fprintf(b, "\treturn MarshalWithType(%q, (*%s)(v))\n}\n\n", c.name, alias)
	}
}

