func emitRequests(s *scheme, outDir string) error {
	var b strings.Builder
	for _, c := range s.functions {
		name := pascal(c.name)
		docComment(&b, name+" —", c.doc)
		fmt.Fprintf(&b, "type %s struct {\n\tReq[%s]\n", name, s.goResult(c.result))
		for _, f := range c.fields {
			fieldDoc(&b, f.doc)
			fmt.Fprintf(&b, "\t%s %s `json:%q`\n", goFieldName(f.name), s.goType(f.typ), jsonTagFor(f))
		}
		fmt.Fprintf(&b, "}\n\n")
		fmt.Fprintf(&b, "// TDType returns the TDLib @type discriminator %q.\n", c.name)
		fmt.Fprintf(&b, "func (%s) TDType() string { return %q }\n\n", name, c.name)
	}
	return writeGo(outDir, "requests_gen.go", b.String())
}

