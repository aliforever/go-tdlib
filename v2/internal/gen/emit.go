// emitScalars writes scalars_gen.go: named types for TL scalars whose JSON
// encoding does not match encoding/json defaults.
func emitScalars(outDir string) error {
	const body = `import (
	"encoding/json"
	"strconv"
)

// Int64List is a TL vector<int64>. TDLib serializes int64 values as JSON
// strings ("123"), and the ,string struct-tag option does not reach slice
// elements, so the conversion is done here. Scalar int64 fields use
// json:"name,string" instead.
type Int64List []int64

// MarshalJSON emits each element as a quoted decimal string.
func (l Int64List) MarshalJSON() ([]byte, error) {
	if l == nil {
		return []byte("null"), nil
	}
	quoted := make([]string, len(l))
	for i, v := range l {
		quoted[i] = strconv.FormatInt(v, 10)
	}
	return json.Marshal(quoted)
}

// UnmarshalJSON accepts quoted elements (what TDLib sends) and, liberally,
// plain JSON numbers.
func (l *Int64List) UnmarshalJSON(data []byte) error {
	var raw []json.RawMessage
	if err := json.Unmarshal(data, &raw); err != nil {
		return err
	}
	out := make([]int64, len(raw))
	for i, r := range raw {
		var s string
		if err := json.Unmarshal(r, &s); err == nil {
			v, err := strconv.ParseInt(s, 10, 64)
			if err != nil {
				return err
			}
			out[i] = v
			continue
		}
		if err := json.Unmarshal(r, &out[i]); err != nil {
			return err
		}
	}
	*l = out
	return nil
}
`
	return writeGo(outDir, "scalars_gen.go", body)
}

