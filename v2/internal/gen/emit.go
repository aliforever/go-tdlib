const header = "// Code generated by internal/gen; DO NOT EDIT.\n\npackage td\n"

// entityChunkSize bounds the generated types files so no single file is
// unwieldy; output stays deterministic because entities are pre-sorted.
const entityChunkSize = 400

func emitAll(s *scheme, outDir string) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	if err := emitScalars(outDir); err != nil {
		return err
	}
	if err := emitEntities(s, outDir); err != nil {
		return err
	}
	if err := emitUnions(s, outDir); err != nil {
		return err
	}
	if err := emitRequests(s, outDir); err != nil {
		return err
	}
	if err := emitUpdates(s, outDir); err != nil {
		return err
	}
	if err := emitSchema(s, outDir); err != nil {
		return err
	}
	return nil
}

func writeGo(outDir, name, body string) error {
	return writeGoFile(outDir, name, header+body)
}

// writeGoFile gofmts and writes a complete generated source file.
func writeGoFile(outDir, name, full string) error {
	formatted, err := format.Source([]byte(full))
	if err != nil {
		return fmt.Errorf("gofmt %s: %w\n---\n%s", name, err, full)
	}
	return os.WriteFile(filepath.Join(outDir, name), formatted, 0o644)
}

// docComment renders a (possibly multi-line) TL description as godoc.
func docComment(b *strings.Builder, name, doc string) {
	if doc == "" {
		return
	}
	for i, line := range strings.Split(doc, "\n") {
		if i == 0 {
			fmt.Fprintf(b, "// %s %s\n", name, line)
		} else {
			fmt.Fprintf(b, "// %s\n", line)
		}
	}
}

// fieldDoc renders a field doc as an indented comment above the field.
func fieldDoc(b *strings.Builder, doc string) {
	if doc == "" {
		return
	}
	for _, line := range strings.Split(doc, "\n") {
		fmt.Fprintf(b, "\t// %s\n", line)
	}
}

