// variantIfaceName derives the sealed variant interface name from the class:
// MessageContent -> messageContentVariant.
func variantIfaceName(class string) string {
	return strings.ToLower(class[:1]) + class[1:] + "Variant"
}

// exportedVariantAliases lists the classes whose sealed variant interface
// also gets an exported alias (type UpdateVariant = updateVariant). The root
// tdlib package needs those names as generic-method constraints
// (Client.On[U], MessageStream.WithContent[T]); a method constraint cannot
// name an unexported interface from another package. The alias does not
// unseal the set: it still carries the unexported is<Class> marker method,
// which only generated code in this package can implement.
var exportedVariantAliases = map[string]bool{
	"Update":         true,
	"MessageContent": true,
}

func emitUnions(s *scheme, outDir string) error {
	// class name -> variants sorted by constructor name
	variants := map[string][]ctor{}
	for _, c := range s.entities {
		if _, ok := s.classes[c.result]; ok {
			variants[c.result] = append(variants[c.result], c)
		}
	}
	classes := make([]string, 0, len(s.classes))
	for class := range s.classes {
		classes = append(classes, class)
	}
	sort.Strings(classes)

	var b strings.Builder
	b.WriteString("import \"encoding/json\"\n\n")
	for _, class := range classes {
		vs := variants[class]
		iface := variantIfaceName(class)

		docComment(&b, iface+" is the sealed variant set of", classDocFallback(s, class))
		fmt.Fprintf(&b, "type %s interface {\n\tTDType() string\n\tis%s()\n}\n\n", iface, class)

		docComment(&b, class+" is the union container for", classDocFallback(s, class))
		fmt.Fprintf(&b, "type %s struct {\n\tUnion[%s]\n}\n\n", class, iface)

		fmt.Fprintf(&b, "// New%s wraps a known %s variant.\n", class, class)
		fmt.Fprintf(&b, "func New%s(v %s) %s {\n\treturn %s{Union: NewUnion[%s](v.TDType(), v)}\n}\n\n", class, iface, class, class, iface)

		// variant marker methods
		for _, v := range vs {
			fmt.Fprintf(&b, "func (*%s) is%s() {}\n", pascal(v.name), class)
		}
		b.WriteString("\n")

		if exportedVariantAliases[class] {
			fmt.Fprintf(&b, "// %sVariant aliases the sealed %s variant set for use as a\n", class, iface)
			fmt.Fprintf(&b, "// generic-method constraint outside this package. The set stays\n")
			fmt.Fprintf(&b, "// sealed: implementing it requires the unexported is%s method.\n", class)
			fmt.Fprintf(&b, "type %sVariant = %s\n\n", class, iface)
		}

		// visitor cases
		fmt.Fprintf(&b, "// %sCases is the visitor table for %s.Match. Leave arms nil\n", class, class)
		fmt.Fprintf(&b, "// to fall through to Unknown.\n")
		fmt.Fprintf(&b, "type %sCases[R any] struct {\n", class)
		for _, v := range vs {
			fmt.Fprintf(&b, "\t%s func(*%s) R\n", pascal(v.name), pascal(v.name))
		}
		fmt.Fprintf(&b, "\tUnknown func(kind string, raw json.RawMessage) R\n}\n\n")

		fmt.Fprintf(&b, "// Match dispatches on the union's @type to the matching case.\n")
		fmt.Fprintf(&b, "func (u %s) Match[R any](cases %sCases[R]) R {\n", class, class)
		fmt.Fprintf(&b, "\tswitch u.Kind() {\n")
		for _, v := range vs {
			name := pascal(v.name)
			fmt.Fprintf(&b, "\tcase %q:\n", v.name)
			fmt.Fprintf(&b, "\t\tif cases.%s != nil {\n", name)
			fmt.Fprintf(&b, "\t\t\tif v, ok := u.Value().(*%s); ok {\n\t\t\t\treturn cases.%s(v)\n\t\t\t}\n\t\t}\n", name, name)
		}
		fmt.Fprintf(&b, "\t}\n")
		fmt.Fprintf(&b, "\tif cases.Unknown != nil {\n\t\treturn cases.Unknown(u.Kind(), u.Raw())\n\t}\n")
		fmt.Fprintf(&b, "\tvar zero R\n\treturn zero\n}\n\n")

		// decoder table
		fmt.Fprintf(&b, "func init() {\n\tRegisterUnion[%s](map[string]unionDecoder{\n", iface)
		for _, v := range vs {
			name := pascal(v.name)
			fmt.Fprintf(&b, "\t\t%q: func(raw json.RawMessage) (any, error) {\n", v.name)
			fmt.Fprintf(&b, "\t\t\tv := new(%s)\n\t\t\treturn v, json.Unmarshal(raw, v)\n\t\t},\n", name)
		}
		fmt.Fprintf(&b, "\t})\n}\n\n")
	}
	return writeGo(outDir, "unions_gen.go", b.String())
}

func classDocFallback(s *scheme, class string) string {
	if d := s.classes[class]; d != "" {
		return class + ": " + d
	}
	return "the abstract TDLib class " + class
}

